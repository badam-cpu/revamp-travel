export type CommunityT = (key: string, vars?: Record<string, string>) => string;

/** The text function for a language: the admin's edits for it, else the built-in text, else the English. */
export function communityText(lang: CommunityLang, edits?: Record<string, string> | null): CommunityT {
  return (key, vars) => {
    const edited = edits?.[key]?.trim();
    let s = edited || (lang === "hy" ? TEXT_HY[key] : undefined) || (TEXT_EN[key] ?? key);
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
    return s;
  };
}

